"""Port eFuses U10-U14 with their dividers, TVS/ESD and connectors J1-J5 (local routing).
EN trees hop on In2 (inside the V5 band), so B.Cu stays free for the FLT/OFF/I2C runs to U8/U9 (r_mux.py)."""
from rt import T, V, VS, Z, rect, PADS, FP
F, B, I2 = 'F.Cu', 'B.Cu', 'In2.Cu'
G = 'GND'
def P(k):
    p = PADS[k]; return (p['x'], p['y'])
def gv(*pads_vias, w=0.3):
    for p, v in pads_vias:
        T(G, w, F, p, v); V(G, *v)
def via(net, pad, v, w=0.25):
    T(net, w, F, pad, v); V(net, *v)

def west(k, U, ENt, ENb, OVt, OVb, Dt, De, J, skip=()):
    n = 'PORT%d_' % k; ux, uy = FP[U]['x'], FP[U]['y']
    T(n + 'OVLO', 0.15, F, U + '.2', (P(OVb + '.1')[0], uy - 0.23))
    T(n + 'OVLO', 0.15, F, OVt + '.2', (P(OVt + '.2')[0], P(OVb + '.1')[1] - 0.02))
    v1, v3 = (ux - 1.4, uy - 1.65), (ux - 3.95, uy + 0.55)
    T(n + 'EN', 0.15, F, U + '.1', (ux - 1.4, uy - 0.7), v1); V(n + 'EN', *v1)
    T(n + 'EN', 0.15, I2, v1, (ux - 3.6, uy + 0.55), v3); V(n + 'EN', *v3)
    e = P(ENb + '.1'); T(n + 'EN', 0.15, F, v3, (e[0] - 0.13, e[1] + 0.3))
    o = P(OVb + '.2'); gv((OVb + '.2', (o[0] - 0.85, o[1])))
    e2 = P(ENb + '.2')
    if 'enb' not in skip: gv((ENb + '.2', (e2[0] - 0.86, e2[1])))
    t1 = P(OVt + '.1')
    if 'ovt' not in skip: via('V5', OVt + '.1', (t1[0] - 0.86, t1[1]))
    # V5_k out: pad 6 north -> pour over the TVS and J pin 1
    if 'pour' not in skip: Z('V5_%d' % k, F, [(ux + 0.1, uy - 1.15), (ux + 0.4, uy - 1.15), (ux + 0.4, uy - 4.3), (ux - 1.0, uy - 4.3),
                       (ux - 1.0, uy - 8.15), (ux - 2.45, uy - 8.15), (ux - 2.45, uy - 2.1), (ux - 0.3, uy - 2.1),
                       (ux + 0.1, uy - 1.7)], 'R_V5P%d_F' % k, prio=4)
    if Dt:
        d2 = P(Dt + '.2'); gv((Dt + '.2', (d2[0], d2[1] - 1.15)))
    if 'j' not in skip:
        j4 = P(J + '.4'); gv((J + '.4', (j4[0], -29.1)))
        d4 = P(De + '.4'); T(G, 0.2, F, (d4[0] + 0.05, d4[1]), (d4[0] + 0.05, -29.1)); V(G, d4[0] + 0.05, -29.1)
    return ux, uy

def esd4(k, De, J, Rscl, Rsda):
    """SCL_C / SDA_C for the 4-pin ports with the ESD part left of the connector"""
    n = 'PORT%d_' % k
    j2, j3, d3, d5 = P(J + '.2'), P(J + '.3'), P(De + '.3'), P(De + '.5')
    T(n + 'SCL_C', 0.15, F, J + '.2', (j2[0], d3[1]), De + '.3')
    rs = P(Rscl + '.2')
    T(n + 'SCL_C', 0.15, F, De + '.3', (d3[0], rs[1] - 0.55), (d3[0] + 0.2, rs[1] - 0.35))
    T(n + 'SDA_C', 0.15, F, J + '.3', (j3[0], -26.4), (d5[0], -25.92), De + '.5')
    return d3, d5

def vpad5(U):
    ux, uy = FP[U]['x'], FP[U]['y']
